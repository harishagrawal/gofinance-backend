func randomStringWithAlphabet(number int, ab string) string {
	if len(ab) == 0 || number <= 0 {
		return ""
	}
	var sb strings.Builder
	k := len(ab)
	for i := 0; i < number; i++ {
		c := ab[rand.Intn(k)]
		sb.WriteByte(c)
	}
	return sb.String()
}