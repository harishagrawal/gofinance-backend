func generateValidJWT(expiry time.Time, claimsFields map[string]any, signingKey []byte, alg jwt.SigningMethod) (string, error) {
	claims := Claims{}
	claims.Username = "john_doe"
	claims.RegisteredClaims.Issuer = "test"
	claims.RegisteredClaims.ExpiresAt = jwt.NewNumericDate(expiry)
	claims.RegisteredClaims.NotBefore = jwt.NewNumericDate(time.Now().Add(-5 * time.Minute))
	claims.RegisteredClaims.Audience = []string{"testaud"}

	if claimsFields != nil {
		val := reflect.ValueOf(&claims).Elem()
		for k, v := range claimsFields {
			field := val.FieldByName(k)
			if field.IsValid() && field.CanSet() {
				field.Set(reflect.ValueOf(v))
			}
		}
	}

	token := jwt.NewWithClaims(alg, claims)
	signed, err := token.SignedString(signingKey)
	return signed, err
}
